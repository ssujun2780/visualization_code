import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {gzipSync,gunzipSync} from 'node:zlib';
import {Session} from 'node:inspector';
import {performance} from 'node:perf_hooks';
import {decodeExecution} from '../../../../scripts/shared/execution-format.mjs';
import {inferStructures,decodeInference} from '../../../../scripts/inference/index.mjs';
import {analyzeRecordingWork} from '../../../../scripts/animation/work-analysis.mjs';
import {prepareStructures} from '../../../../src/animation/prepared-structures.js';
const [id,stage]=process.argv.slice(2);
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../../..');
const dir=path.join(root,'test-results/codex_code-results/end_to_end_audit_20261113',id);
const progress=stageName=>fs.writeFile(path.join(dir,'profile-'+stage+'-progress.json'),JSON.stringify({stage:stageName,at:new Date().toISOString()}));
await progress('load-execution');
const r=decodeExecution(JSON.parse(gunzipSync(await fs.readFile(path.join(dir,'execution.json.gz')))));
await progress('load-inference');
const inference=decodeInference(JSON.parse(gunzipSync(await fs.readFile(path.join(dir,'inference.json.gz')))));
await progress('profiler-start');
const session=new Session();session.connect();
const post=(method,params={})=>new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(new Error('Profiler request timeout: '+method)),5000);session.post(method,params,(error,v)=>{clearTimeout(timer);error?reject(error):resolve(v);});});
await post('Profiler.enable');await post('Profiler.setSamplingInterval',{interval:2000});
global.gc?.();await post('Profiler.start');
await progress('execute-stage');
const started=performance.now();
let result;
if(stage==='inference')result=inferStructures(r.plan,r.trace,{observationPlan:r.observations?.plan,observedTrace:r.observations?.trace});
else if(stage==='work')result=analyzeRecordingWork(r.plan,r.trace,{ast:r.ast,observations:r.observations,structureInference:inference});
else if(stage==='prepare')result=prepareStructures(r.plan,r.trace,inference);
else throw new Error('Unknown stage');
const ms=performance.now()-started,{profile}=await post('Profiler.stop');session.disconnect();
await fs.writeFile(path.join(dir,'profile-'+stage+'.json.gz'),gzipSync(JSON.stringify(profile)));
const nodes=new Map(profile.nodes.map(n=>[n.id,n])),counts=new Map();
for(let i=0;i<(profile.samples?.length??0);i++){
 const n=nodes.get(profile.samples[i]),f=n.callFrame,key=(f.url?.split('/').slice(-3).join('/')??'')+':'+(f.lineNumber+1)+' '+(f.functionName||'(anonymous)');
 counts.set(key,(counts.get(key)??0)+(profile.timeDeltas?.[i]??2000));
}
const total=[...counts.values()].reduce((a,b)=>a+b,0);
const summary={id,stage,ms,maxRssKiB:process.resourceUsage().maxRSS,top:[...counts].sort((a,b)=>b[1]-a[1]).slice(0,15).map(([location,microseconds])=>({location,ms:microseconds/1000,percent:microseconds/total*100})),status:result.status??result.relations?.status};
await fs.writeFile(path.join(dir,'profile-'+stage+'-summary.json'),JSON.stringify(summary,null,2));
console.log(JSON.stringify(summary));
